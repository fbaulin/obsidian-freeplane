import { nodeTextSource } from "./mm/xml";
import { Plugin, TFile, Notice, MarkdownView, WorkspaceLeaf } from "obsidian";
import { parseMm, richContentSource } from "./mm/xml";
import { FreeplaneView, VIEW_TYPE_FREEPLANE } from "./FreeplaneView";

import { settings } from "./settings";
const marker = "<!-- Generated by obsidian-freeplane; edits will be overwritten. -->";

export function installSearchIndex(plugin: Plugin) {
  const app = plugin.app;
  let folder = settings.searchIndexFolder;
  let queue = Promise.resolve();
  const indexPath = (path: string) => `${folder}/${path}.md`;
  const openNode = async (leaf: WorkspaceLeaf, file: TFile, id: string) => {
    await leaf.setViewState({ type: VIEW_TYPE_FREEPLANE, state: { file: file.path }, active: true });
    await app.workspace.revealLeaf(leaf);
    if (leaf.view instanceof FreeplaneView) leaf.view.revealNode(id);
  };
  // Open the map from an index result. Use the plugin search to locate text;
  // do not intercept WorkspaceLeaf methods or depend on search selection state.
  plugin.registerEvent(app.workspace.on("file-open", file => {
    if (!file || !file.path.startsWith(folder + "/")) return;
    const leaf = app.workspace.activeLeaf;
    if (!leaf) return;
    window.setTimeout(() => { void (async () => {
      const view = leaf.view;
      if (!(view instanceof MarkdownView) || view.file !== file) return;
      const text = await app.vault.read(file);
      if (!text.startsWith(marker) || leaf.view !== view) return;
      const url = /obsidian:\/\/freeplane-node\?[^)\s]+/.exec(text)?.[0];
      if (!url) return;
      const params = new URL(url).searchParams;
      const id = params.get("node") || "";
      const map = app.vault.getAbstractFileByPath(params.get("file") || "");
      if (map instanceof TFile) await openNode(leaf, map, id);
    })().catch(err => { console.error(err); new Notice("Could not open matching map node."); }); }, 0);
  }));
  const enqueue = (work: () => Promise<void>) => {
    queue = queue.then(work).catch(err => { console.error("Freeplane index", err); new Notice("Freeplane search index could not be updated."); });
  };
  const update = async (file: TFile) => {
    if (file.extension !== "mm") return;
    const doc = parseMm(await app.vault.read(file));
    const rows = [marker, `# ${file.basename}`, ""];
    for (const node of Array.from(doc.querySelectorAll("node"))) {
      const id = node.getAttribute("ID");
      if (!id) continue;
      const url = `obsidian://freeplane-node?vault=${encodeURIComponent(app.vault.getName())}&file=${encodeURIComponent(file.path)}&node=${encodeURIComponent(id)}`;
      const contents = [nodeTextSource(node) || "Untitled node", richContentSource(node, "DETAILS"), richContentSource(node, "NOTE")];
      rows.push(`## ${id}`);
      for (const content of contents) for (const line of content.split(/\r?\n/).filter(Boolean)) {
        const label = line.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/([\\[\]*_`])/g, "\\$1");
        rows.push(`[${label}](${url})`, "");
      }
    }
    const dirs = indexPath(file.path).split("/").slice(0, -1);
    for (let i = 1; i <= dirs.length; i++) {
      const dir = dirs.slice(0, i).join("/");
      if (!app.vault.getAbstractFileByPath(dir)) await app.vault.createFolder(dir);
    }
    const path = indexPath(file.path), existing = app.vault.getAbstractFileByPath(path), text = rows.join("\n");
    if (existing instanceof TFile) {
      const old = await app.vault.read(existing);
      if (!old.startsWith(marker)) throw new Error("Index filename is occupied by a user note: " + path);
      if (old !== text) await app.vault.modify(existing, text);
    } else await app.vault.create(path, text);
    // Retire only our generated legacy encoded index, leaving user notes alone.
    const legacyPath = `${folder}/${encodeURIComponent(file.path)}.md`;
    const legacy = app.vault.getAbstractFileByPath(legacyPath);
    if (legacyPath !== path && legacy instanceof TFile && (await app.vault.read(legacy)).startsWith(marker))
      await app.vault.trash(legacy, true);
  };
  const remove = async (path: string) => {
    const file = app.vault.getAbstractFileByPath(indexPath(path));
    if (file instanceof TFile && (await app.vault.read(file)).startsWith(marker)) await app.vault.trash(file, true);
  };
  plugin.registerObsidianProtocolHandler("freeplane-node", async params => {
    if (params.vault && params.vault !== app.vault.getName()) return;
    const file = app.vault.getAbstractFileByPath(params.file || "");
    if (!(file instanceof TFile) || file.extension !== "mm") return;
    const leaf = app.workspace.getLeavesOfType(VIEW_TYPE_FREEPLANE).find(l => (l.view as FreeplaneView).file?.path === file.path) || app.workspace.getLeaf("tab");
    await openNode(leaf, file, params.node);
  });
  plugin.registerEvent(app.vault.on("create", file => { if (file instanceof TFile && file.extension === "mm") enqueue(() => update(file)); }));
  plugin.registerEvent(app.vault.on("modify", file => { if (file instanceof TFile && file.extension === "mm") enqueue(() => update(file)); }));
  plugin.registerEvent(app.vault.on("rename", (file, old) => { if (file instanceof TFile && (file.extension === "mm" || old.endsWith(".mm"))) enqueue(async () => { await remove(old); await update(file); }); }));
  plugin.registerEvent(app.vault.on("delete", file => { if (file instanceof TFile && file.extension === "mm") enqueue(() => remove(file.path)); }));
  app.workspace.onLayoutReady(() => { for (const file of app.vault.getFiles()) if (file.extension === "mm") enqueue(() => update(file)); });
  return (nextFolder: string): Promise<void> => {
    const task = queue.then(async () => {
      if (nextFolder === folder) return;
      if (app.vault.getAbstractFileByPath(nextFolder)) throw new Error("That folder name is already in use. Choose an unused name.");
      const existing = app.vault.getAbstractFileByPath(folder);
      if (existing) await app.vault.rename(existing, nextFolder);
      else await app.vault.createFolder(nextFolder);
      folder = nextFolder;
    });
    queue = task.catch(err => { console.error("Freeplane index folder", err); });
    return task;
  };

}
